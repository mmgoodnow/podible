import assert from "node:assert/strict";
import { chromium } from "playwright";
const server = Bun.spawn([process.execPath, "run", "test/fixtures/recovery-spa-server.ts"], { stdout: "pipe", stderr: "inherit" });
let browser: Awaited<ReturnType<typeof chromium.launch>> | undefined;
try {
  const reader = server.stdout.getReader();
  let output = "", origin = "";
  const deadline = Date.now() + 20000;
  while (!origin) {
    const part = await Promise.race([reader.read(), Bun.sleep(Math.max(1, deadline - Date.now())).then(() => { throw new Error("Recovery fixture startup timed out"); })]);
    output += new TextDecoder().decode(part.value);
    const value = /RECOVERY_FIXTURE=(.+)/.exec(output)?.[1];
    if (value) origin = JSON.parse(value).url;
    if (part.done && !origin) throw new Error("Recovery fixture exited");
  }
  reader.releaseLock();
  void (async () => { const drain = server.stdout.getReader(); while (!(await drain.read()).done) {} })();
  browser = await chromium.launch({ ...(process.env.CI ? {} : { channel: "chrome" }), headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  context.setDefaultTimeout(15000);
  await context.addCookies([{ name: "podible_session", value: "recovery-admin", url: origin, httpOnly: true }]);
  const page = await context.newPage();
  const errors: string[] = [];
  const inventoryRequests: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", request => { if (request.url().includes("recovery.inventory")) inventoryRequests.push(request.url()); });
  await page.goto(new URL("/recovery", origin).href);
  await page.getByRole("heading", { name: "Restore missing media", exact: true }).waitFor();
  await page.getByText("Repairable movie", { exact: true }).waitFor();
  await page.getByText("Repair links", { exact: true }).waitFor();
  assert.equal(await page.getByText("Healthy owned movie", { exact: true }).count(), 0, "Healthy selected bytes and links should be omitted, including missing unselected history");
  assert.equal(await page.getByText("Initial pending movie", { exact: true }).count(), 0, "An initial pending request is not confirmed loss");
  assert.equal(await page.locator(".recovery-resource").count(), 1);
  assert.equal(inventoryRequests.length, 1, "Recovery automatically scanned more than its first bounded page");
  await page.getByRole("button", { name: "Check again", exact: true }).waitFor();
  await page.getByText("More titles have not been checked.", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Check next 20", exact: true }).waitFor();
  const before = await (await context.request.get(new URL("/__fixture/verify", origin).href)).json();
  assert.equal(before.repaired, false, "Read-only inventory unexpectedly repaired a link");
  await page.getByRole("button", { name: "Select recoverable" }).click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Recover selected (1)", exact: true }).click();
  await page.getByRole("region", { name: "Recovery results" }).getByText("Repairable movie: Links repaired", { exact: true }).waitFor();
  await page.getByText("No missing files or broken links found among these 20 checked titles.", { exact: true }).waitFor();
  assert.equal(await page.locator(".recovery-resource").count(), 0, "The repaired title remained in the missing-content list");
  assert.equal(await page.locator(".recovery-actions").count(), 0, "An empty missing-content list should hide bulk actions");
  assert.equal(await page.getByText("Healthy owned movie", { exact: true }).count(), 0);
  await page.getByRole("button", { name: "Check next 20", exact: true }).click();
  await page.getByText("No missing files or broken links found among these 1 checked titles.", { exact: true }).waitFor();
  await page.getByRole("region", { name: "Recovery results" }).getByText("Repairable movie: Links repaired", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Check next 20", exact: true }).count(), 0);
  const after = await (await context.request.get(new URL("/__fixture/verify", origin).href)).json();
  assert.deepEqual(after, { repaired: true, preserved: true, healthyPreserved: true, tvMountStillMissing: true });
  await page.getByRole("group", { name: "Recovery media type" }).getByRole("button", { name: "TV", exact: true }).click();
  const unchecked = page.locator("details").filter({ has: page.locator("summary", { hasText: "Could not check (1)" }) });
  await unchecked.locator("summary").waitFor();
  assert.equal(await unchecked.getAttribute("open"), null, "Uncheckable mounts should start collapsed");
  assert.equal(await page.locator(".recovery-resource").count(), 0, "A missing mount is unknown, not confirmed missing content");
  assert.equal(await page.getByText("Cannot repair yet", { exact: true }).count(), 0);
  await unchecked.locator("summary").click();
  await unchecked.getByRole("heading", { name: "A Work", exact: true }).waitFor();
  await unchecked.getByText("Owned mount is missing", { exact: false }).waitFor();
  await page.getByText("No titles could be checked.", { exact: true }).waitFor();
  await unchecked.getByText("We couldn't verify these titles. They may still be available.", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "Select recoverable" }).count(), 0);
  const member = await browser.newContext();
  await member.addCookies([{ name: "podible_session", value: "recovery-reader", url: origin, httpOnly: true }]);
  const memberPage = await member.newPage();
  await memberPage.goto(new URL("/recovery", origin).href);
  await memberPage.getByRole("alert").getByText("Administrator access required.", { exact: true }).waitFor();
  const denied = await member.request.post(new URL("/rpc", origin).href, { data: { jsonrpc: "2.0", id: 1, method: "recovery.inventory", params: { namespace: "movie-target" } } });
  assert.equal((await denied.json()).error.code, -32003);
  await page.getByRole("navigation", { name: "Main navigation" }).getByRole("link", { name: "Activity", exact: true }).click();
  await page.getByRole("heading", { name: "Activity", exact: true }).waitFor();
  await page.getByRole("link", { name: "Review torrent problems", exact: true }).click();
  await page.getByRole("heading", { name: "Torrent health", exact: true }).waitFor();
  await page.getByText("No matching private Transmission bindings on this page.", { exact: true }).waitFor();
  await page.getByRole("heading", { name: "Automatic cleanup", exact: true }).waitFor();
  await page.getByText("No matching private bindings on this page.", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: /remove|retire/i }).count(), 0, "Retirement preview exposed a direct removal command");
  const receipts = () => context.request.get(new URL("/__fixture/stewardship", origin).href).then(r => r.json());
  assert.equal((await receipts()).receipts, 0, "Stewardship page load collected or wrote to daemon state");
  await page.getByRole("button", { name: "Collect next batch", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "Collected 0 observation(s)" }).waitFor();
  assert.equal((await receipts()).receipts, 1);
  await memberPage.goto(new URL("/stewardship", origin).href);
  await memberPage.getByRole("alert").getByText("Administrator access required.", { exact: true }).waitFor();
  const deniedCollection = await member.request.post(new URL("/rpc", origin).href, { data: { jsonrpc: "2.0", id: 2, method: "stewardship.collect", params: { operationId: crypto.randomUUID() } } });
  assert.equal((await deniedCollection.json()).error.code, -32003);
  const deniedRetirement = await member.request.post(new URL("/rpc", origin).href, { data: { jsonrpc: "2.0", id: 4, method: "torrentRetirement.preview", params: {} } });
  assert.equal((await deniedRetirement.json()).error.code, -32003);
  let tvAudits = 0;
  page.on("request", request => { if (request.url().includes("tvRetention.audit")) tvAudits++; });
  await page.goto(new URL("/tv-retention", origin).href);
  await page.getByRole("heading", { name: "Whole-season TV retention", exact: true }).waitFor();
  assert.equal(tvAudits, 0, "Opening TV retention started an audit without an explicit request");
  const seasons = page.getByRole("combobox", { name: "TV title and season", exact: true });
  await seasons.getByRole("option", { name: "A Work (2020) / Season 1", exact: true }).waitFor({ state: "attached" });
  assert.deepEqual(await seasons.getByRole("option").allTextContents(), ["Choose a title and season", "A Work (2020) / Season 1"], "Unrequested catalog seasons entered the retention picker");
  assert.equal(await page.getByRole("spinbutton").count(), 0, "TV retention still requires numeric target IDs");
  await seasons.selectOption({ label: "A Work (2020) / Season 1" });
  assert.equal(tvAudits, 0, "Choosing a TV title started an audit before confirmation");
  await page.getByRole("button", { name: "Audit entire season", exact: true }).click();
  await page.getByRole("heading", { name: "Season removal blocked", exact: true }).waitFor();
  assert.equal(tvAudits, 1);
  assert.equal(await page.getByRole("button", { name: "Evict complete single-season target", exact: true }).count(), 0);
  const technical = page.locator("details").filter({ has: page.locator("summary", { hasText: "Watch, file and operation details" }) });
  assert.equal(await technical.count(), 1);
  assert.equal(await technical.getAttribute("open"), null, "Raw watch/file details should start collapsed");
  assert.equal(await page.getByRole("heading", { name: "Exact episode history", exact: true }).isVisible(), false);
  await technical.locator("summary").click();
  await page.getByRole("heading", { name: "Exact episode history", exact: true }).waitFor();
  await memberPage.goto(new URL("/tv-retention", origin).href);
  await memberPage.getByRole("alert").getByText("Administrator access required.", { exact: true }).waitFor();
  const deniedTvAudit = await member.request.post(new URL("/rpc", origin).href, { data: { jsonrpc: "2.0", id: 3, method: "tvRetention.audit", params: { targetId: 1, seasonNumber: 1 } } });
  assert.equal((await deniedTvAudit.json()).error.code, -32003);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate("document.documentElement.scrollWidth > innerWidth"), false);
  assert.deepEqual(errors, []);
  console.log("Recovery, stewardship and TV retention Chrome acceptance passed: read-only previews, explicit link repair, preserved bytes/inode, missing-mount blocking, explicit observation receipts, whole-season audit without unsafe eviction, actual RPC authorization, deep links and mobile layout.");
} finally { await browser?.close(); server.kill("SIGTERM"); await server.exited; }

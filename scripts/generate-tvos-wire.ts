type Shape = {
  type?: string;
  properties?: Record<string, Shape>;
  required?: string[];
  enum?: string[];
  anyOf?: Shape[];
  items?: Shape;
};
type Fields = { [key: string]: true | Fields };

const swiftIdentifier = (value: string) => {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(value)) throw new Error(`Unsupported Swift identifier: ${value}`);
  return value;
};

function declaration(name: string, schema: z.ZodType, select?: Fields, input = false) {
  const root = z.toJSONSchema(schema, { target: "draft-2020-12", io: input ? "input" : "output" }) as Shape;
  return objectDeclaration(name, root, select, "", !select);
}

function objectDeclaration(name: string, root: Shape, select: Fields | undefined, indent: string, typedEnums: boolean): string {
  if (root.type !== "object") throw new Error(`${name} must be an object`);
  const fields: string[] = [];
  const nested: string[] = [];
  for (const key of Object.keys(select ?? root.properties ?? {})) {
    const shape = root.properties?.[key];
    if (!shape) throw new Error(`Missing wire schema for ${name}.${key}`);
    const nullable = shape.anyOf?.find(branch => branch.type === "null");
    const value = nullable ? shape.anyOf?.find(branch => branch.type !== "null") : shape;
    const fieldName = swiftIdentifier(key[0]!.toUpperCase() + key.slice(1)) + "Value";
    const projection = select?.[key];
    const fieldType = (node: Shape | undefined): string => {
      if (node?.enum && typedEnums) {
        const enumName = swiftIdentifier(key[0]!.toUpperCase() + key.slice(1));
        nested.push(`${indent}    enum ${enumName}: String, Codable, Sendable { case ${node.enum.map(swiftIdentifier).join(", ")} }`);
        return enumName;
      }
      switch (node?.type) {
        case "array": return `[${fieldType(node.items)}]`;
        case "object":
          nested.push(objectDeclaration(fieldName, node, projection === true ? undefined : projection, indent + "    ", typedEnums));
          return fieldName;
        case "string": return "String";
        case "integer": return "Int";
        case "number": return "Double";
        case "boolean": return "Bool";
        default: throw new Error(`Unsupported wire schema for ${name}.${key}`);
      }
    };
    fields.push(`${indent}    let ${swiftIdentifier(key)}: ${fieldType(value)}${nullable || !root.required?.includes(key) ? "?" : ""}`);
  }
  return [`${indent}${indent ? "" : "nonisolated "}struct ${name}: Codable, Sendable {`, ...nested, ...fields, `${indent}}`].join("\n");
}


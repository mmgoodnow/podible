import { z } from "zod";
import { authRouter } from "../src/rpc/auth-router";

type Shape = {
  type?: string;
  properties?: Record<string, Shape>;
  required?: string[];
  enum?: string[];
  anyOf?: Shape[];
};

const swiftIdentifier = (value: string) => {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(value)) throw new Error(`Unsupported Swift identifier: ${value}`);
  return value;
};

function declaration(name: string, schema: z.ZodType) {
  const root = z.toJSONSchema(schema, { target: "draft-2020-12" }) as Shape;
  if (root.type !== "object") throw new Error(`${name} must be an object`);
  const fields: string[] = [];
  const nested: string[] = [];
  for (const [key, shape] of Object.entries(root.properties ?? {})) {
    const nullable = shape.anyOf?.find(branch => branch.type === "null");
    const value = nullable ? shape.anyOf?.find(branch => branch.type !== "null") : shape;
    let type = { string: "String", integer: "Int", boolean: "Bool" }[value?.type as "string" | "integer" | "boolean"];
    if (value?.enum) {
      type = swiftIdentifier(key[0]!.toUpperCase() + key.slice(1));
      nested.push(`    enum ${type}: String, Codable, Sendable { case ${value.enum.map(swiftIdentifier).join(", ")} }`);
    }
    if (!type) throw new Error(`Unsupported wire schema for ${name}.${key}`);
    fields.push(`    let ${swiftIdentifier(key)}: ${type}${nullable || !root.required?.includes(key) ? "?" : ""}`);
  }
  return [`nonisolated struct ${name}: Codable, Sendable {`, ...nested, ...fields, "}"].join("\n");
}

const { beginDeviceLogin, exchangeDeviceLogin, logout } = authRouter.routes;
const body = [
  "// Generated by bun run generate:tvos-wire. Do not edit.",
  declaration("DeviceLoginGrant", beginDeviceLogin.resultSchema),
  declaration("DeviceLoginExchange", exchangeDeviceLogin.resultSchema),
  declaration("PairingExchangeInput", exchangeDeviceLogin.paramsSchema),
  declaration("LogoutReceipt", logout.resultSchema),
].join("\n\n") + "\n";
const destination = new URL("../tvos/PodibleTV/RPCWire.swift", import.meta.url);
if (process.argv.includes("--check")) {
  if (await Bun.file(destination).text().catch(() => "") !== body) {
    console.error("tvOS RPC contracts changed. Run bun run generate:tvos-wire.");
    process.exitCode = 1;
  }
} else {
  await Bun.write(destination, body);
}

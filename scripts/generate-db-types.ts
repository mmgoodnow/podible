import { Database } from "bun:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { finalizeJobJournalMigration, runMigrations } from "../src/db";

interface Table {
  name: string;
  type: string;
  wr: number;
  strict: number;
}

interface Column {
  cid: number;
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
  hidden: number;
}

const HEADER = `// Generated by bun run generate:db-types. Do not edit.
// Source: runMigrations + finalizeJobJournalMigration on an isolated in-memory database.
// App schema only; Reflow owns its separate persistence. No production DB is opened.
// INTEGER/REAL -> number (the app connection's default), TEXT -> string, BLOB -> Uint8Array.
// JSON, dates, booleans and CHECK enums remain SQLite scalar types, not domain types.
// Types describe declared storage, not validation of existing dynamically typed SQLite values.
// Nullable text/composite primary keys are NOT assumed to be NOT NULL.
// Unsupported types, views and virtual/generated columns fail generation for explicit review.
import type { Generated } from "kysely";

`;

/** Introspect only declared storage; do not guess JSON shapes, CHECK enums or affinities. */
export function renderDatabaseTypes(db: Database): string {
  const tables = db.query<Table, []>(
    `SELECT name, type, wr, strict FROM pragma_table_list
     WHERE schema = 'main' AND substr(name, 1, 7) <> 'sqlite_'
     ORDER BY name COLLATE BINARY`
  ).all();
  const lines = [HEADER.trimEnd(), "", "export interface DB {"];
  for (const table of tables) {
    if (table.type !== "table") throw new Error(`Unsupported schema object ${table.name}: ${table.type}`);
    const columns = db.query<Column, [string]>("SELECT * FROM pragma_table_xinfo(?) ORDER BY cid").all(table.name);
    const primaryKey = columns.filter((column) => column.pk > 0);
    const hasPrimaryIndex = db.query("SELECT 1 FROM pragma_index_list(?) WHERE origin = 'pk'").get(table.name) !== null;
    // A real rowid alias has no separate PK index. This also handles INTEGER PRIMARY KEY DESC.
    const rowidAlias = !table.wr && !hasPrimaryIndex && primaryKey.length === 1 && primaryKey[0].type.toUpperCase() === "INTEGER"
      ? primaryKey[0].name : null;
    lines.push(`  ${JSON.stringify(table.name)}: {`);
    for (const column of columns) {
      if (column.hidden !== 0) throw new Error(`Unsupported hidden/generated column ${table.name}.${column.name}`);
      const declared = column.type.trim().toUpperCase();
      let scalar: string;
      switch (declared) {
        case "TEXT": scalar = "string"; break;
        case "INTEGER":
        case "REAL": scalar = "number"; break;
        case "BLOB": scalar = "Uint8Array"; break;
        default: throw new Error(`Unsupported declared type ${JSON.stringify(column.type)} on ${table.name}.${column.name}`);
      }
      const isRowid = column.name === rowidAlias;
      const nullable = !column.notnull && !isRowid && !(column.pk && (table.wr || table.strict));
      const valueType = scalar + (nullable ? " | null" : "");
      const type = isRowid || column.dflt_value !== null ? `Generated<${valueType}>` : valueType;
      lines.push(`    ${JSON.stringify(column.name)}: ${type};`);
    }
    lines.push("  };", "");
  }
  if (tables.length) lines.pop();
  lines.push("}", "");
  return lines.join("\n");
}

export function generateDatabaseTypes(): string {
  using db = new Database(":memory:");
  runMigrations(db);
  // A fresh DB has no jobs to backfill; app startup normally finalizes this after journal migration.
  finalizeJobJournalMigration(db);
  return renderDatabaseTypes(db);
}

/** Check never writes the destination; exported to test drift handling without changing tracked files. */
export function updateDatabaseTypes(output: URL, check: boolean): void {
  const generated = generateDatabaseTypes();
  if (check) {
    let current: string;
    try {
      current = readFileSync(output, "utf8");
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      throw new Error("DB types are missing. Run bun run generate:db-types");
    }
    if (current !== generated) throw new Error("DB types are stale. Run bun run generate:db-types");
  } else {
    writeFileSync(output, generated);
  }
}

if (import.meta.main) {
  const args = Bun.argv.slice(2);
  if (args.some((arg) => arg !== "--check") || args.length > 1) {
    throw new Error("Usage: bun run scripts/generate-db-types.ts [--check]");
  }
  updateDatabaseTypes(new URL("../src/db/schema.ts", import.meta.url), args.includes("--check"));
}
